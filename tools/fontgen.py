"""Rasterise the English font to tbl/vwf_font.txt, the table the build reads. Needs Pillow; the build does not.

    python -X utf8 tools/fontgen.py [fonts/PixelOperator.ttf] [tbl/vwf_font.txt]

One block per character: `char <codepoint> <advance px>`, then one row per pixel, # ink, . empty, ROWS rows.
Edit a glyph by hand in the output if needed; rerunning this overwrites those edits.
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
ROWS = 16
SIZE = 16  # the face's native bitmap size: anything else blurs


def main():
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "fonts/PixelOperator.ttf"
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "tbl/vwf_font.txt"
    font = ImageFont.truetype(str(src), SIZE)
    lines = [f"# {src.name} at {SIZE} px, generated by tools/fontgen.py"]
    for code in range(32, 127):
        ch = chr(code)
        adv = round(font.getlength(ch))
        im = Image.new("L", (adv + 4, ROWS), 0)
        draw = ImageDraw.Draw(im)
        draw.fontmode = "1"
        draw.text((0, 0), ch, font=font, fill=255)
        lines.append(f"char {code} {adv}")
        lines += ["".join("#" if im.getpixel((x, y)) > 127 else "." for x in range(adv)) for y in range(ROWS)]
    out.write_text("\n".join(lines) + "\n", encoding="utf8", newline="\n")
    print(f"{out}: {code - 31} glyphs")


if __name__ == "__main__":
    main()
